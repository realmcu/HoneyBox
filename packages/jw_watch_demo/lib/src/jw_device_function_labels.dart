List<JWDeviceFunction> jwSupportedFunctionsSorted(JWDeviceFunctionInfo info) {
  final supported = info.supported.toList();
  supported.sort(
    (a, b) => jwDeviceFunctionLabel(a).compareTo(jwDeviceFunctionLabel(b)),
  );
  return supported;
}
