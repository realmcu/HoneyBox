"""Refresh read-only address metadata from HoneyProtocol's concrete examples.
Run from anywhere; inspect the generated diff when the normative RST changes.
Executable codecs always take precedence over this unimplemented inventory.
"""
from pathlib import Path
import re
sdk = Path(__file__).resolve().parents[1]
protocol = sdk.parents[2] / 'HoneyProtocol/docs/protocol'
if not protocol.is_dir():
    raise SystemExit(f'HoneyProtocol source directory not found: {protocol}')
entries = {}
for path in sorted(protocol.glob('0x*.rst')):
    cmd = int(path.name.split('-')[0], 16)
    text = path.read_text()
    # Only concrete command tables have a protocol-table command-detail class.
    for table in re.split(r'(?=\.\. list-table::)', text):
        if 'command-detail' not in table.split('\n\n', 1)[0]:
            continue
        for row in re.split(r'\n   \* - ', table)[1:]:
            cells = re.split(r'\n     - ', row)
            direction = next((c for c in cells if '→' in c and ('手机' in c or 'App' in c)), None)
            if direction is None:
                continue
            match = next((re.search(r'``([0-9A-Fa-f]{2}(?: [0-9A-Fa-f]{2}){4,})', c) for c in cells if re.search(r'``([0-9A-Fa-f]{2}(?: [0-9A-Fa-f]{2}){4,})', c)), None)
            if not match:
                continue
            data = bytes.fromhex(match.group(1))
            if data[0] != cmd or data[1] & 15:
                continue
            version, key = data[1] >> 4, data[2]
            opcode = data[5] if cmd == 2 and len(data) > 5 else None
            if cmd == 2 and opcode is None:
                continue
            tx = bool(re.search(r'(手机|App).*→', direction.split('\n')[0]))
            name = re.sub(r'[`*\\]', '', cells[2 if cmd == 2 else 1]).strip().split('\n')[0]
            identity = (cmd, version, key, opcode, tx)
            entries.setdefault(identity, (name, path.stem))
if not entries:
    raise SystemExit('No concrete command examples found; refusing to overwrite catalog')
lines = ["// Generated by tool/generate_protocol_catalog.py from HoneyProtocol RST examples.",
         "// Metadata only: no executable protocol or fabricated reply is generated.",
         "import 'address.dart';", "import 'protocol.dart';", "import 'status.dart';", "",
         "abstract final class WSProtocolCatalog {", "  static const reservedCommands = {0x07, 0x0b, 0x0e, 0x0f};",
         "  static const reservedSettingKeys = {0x43,0x47,0x4b,0x4f,0x53,0x57,0x5b,0x5f};",
         "  // dart format off", "  static const _addresses = <(int,int,int,int?,bool,String,String)>["]
def dart_string(value):
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'").replace('$', r'\$') + "'"
for (cmd, version, key, opcode, tx), (name, ref) in entries.items():
    lines.append(f"    ({cmd},{version},{key},{'null' if opcode is None else opcode},{str(tx).lower()},{dart_string(name)},{dart_string(ref + f'#0x{key:02x}')}),")
lines += ["  ];", "  // dart format on", "  static final entries = <WSProtocolEntry>[",
          "    for(final row in _addresses)",
          "      WSProtocolEntry(address:WSProtocolAddress(cmd:row.$1,version:row.$2,key:row.$3,settingOpcode:row.$4,direction:row.$5?WSWireDirection.phoneToDevice:WSWireDirection.deviceToPhone),name:row.$6,specRef:row.$7,status:WSProtocolStatus.unimplemented,reason:'规范已定义，本阶段仅提供 Raw 联调；无业务编解码器',maxRetries:0),",
          "    for(final cmd in reservedCommands)", "      for(final direction in WSWireDirection.values)", "        WSProtocolEntry(address:WSProtocolAddress(cmd:cmd,version:0,key:0,direction:direction),name:'保留 Command（全部 Version / Key）',specRef:'index',status:WSProtocolStatus.reserved,reason:'HoneyProtocol index：整个 Command 保留，禁止发送'),",
          "    for(final key in reservedSettingKeys)", "      for(final direction in WSWireDirection.values)", "        WSProtocolEntry(address:WSProtocolAddress(cmd:2,version:0,key:key,settingOpcode:0,direction:direction),name:'保留健康设置 Key（全部操作码）',specRef:'0x02-settings#cmd-02-section-3',status:WSProtocolStatus.reserved,reason:'健康监测每组第四个 Key 保留，禁止发送'),", "  ];", "}"]
(sdk / 'lib/src/protocol/catalog.dart').write_text('\n'.join(lines) + '\n')
print(f'{len(entries)} documented addresses; reserved ranges included separately')
