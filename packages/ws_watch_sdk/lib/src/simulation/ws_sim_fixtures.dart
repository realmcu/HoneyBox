  static Uint8List reanchorToToday(Uint8List value) {
    final delta = _todayAnchorSeconds() - anchorEpochSeconds;
    if (delta == 0) return Uint8List.fromList(value);
    final out = Uint8List.fromList(value);
    final data = ByteData.sublistView(out);
    for (var i = 0; i <= out.length - 4; i++) {
      final u = data.getUint32(i, Endian.little);
      if (u >= _epochPatchLo && u <= _epochPatchHi) {
        data.setUint32(i, u + delta, Endian.little);
        i += 3;
      }
    }
    return out;
  }

